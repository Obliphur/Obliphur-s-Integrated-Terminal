"""人设文件夹里 README.md 的文案 (中 / 英两份). 前置 prompt 由 comm.py 传进来, 避免循环导入."""

import i18n

def readme_text(prefix: str) -> str:
    """人设文件夹里的 README.md: 跟随界面语言 (中文 / English)."""
    return _readme_en(prefix) if i18n.is_en() else _readme_zh(prefix)


